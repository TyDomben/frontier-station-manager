// Get technologies by category
export const getTechsByCategory = (category: TechCategory): Technology[] => {
  return TECHNOLOGIES.filter((tech) => tech.category === category);
};

// Get available technologies (prerequisites met)
export const getAvailableTechs = (unlockedTechs: { [id: string]: boolean }): Technology[] => {
  return TECHNOLOGIES.filter((tech) => {
    if (unlockedTechs[tech.id]) return false; // Already unlocked
    return tech.prerequisites.every((prereq) => unlockedTechs[prereq]);
  });
};

// Get tech by ID
export const getTechById = (id: string): Technology | undefined => {
  return TECHNOLOGIES.find((tech) => tech.id === id);
};

// Get total tech count
export const getTotalTechCount = (): number => {
  return TECHNOLOGIES.length;
};

// Calculate total research cost for all techs
export const getTotalResearchCost = (): number => {
  return TECHNOLOGIES.reduce((sum, tech) => sum + tech.researchCost, 0);
};
