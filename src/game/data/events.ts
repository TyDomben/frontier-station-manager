import {
  EventCategory,
  EventSeverity,
  ResourceType,
  SkillType,
} from '@/core/types';

export interface EventDefinition {
  id: string;
  type: string;
  category: EventCategory;
  severity: EventSeverity;
  title: string;
  description: string;
  probability: number; // Base probability per day
  choices?: {
    id: string;
    text: string;
    effects: EventEffectDef[];
    requirements?: {
      resource?: { type: ResourceType; amount: number };
      skill?: { type: SkillType; level: number };
    };
  }[];
  effects: EventEffectDef[];
  conditions?: EventCondition[];
}

export interface EventEffectDef {
  type: 'resource' | 'crew' | 'room' | 'reputation' | 'research' | 'spawn' | 'morale' | 'health';
  value?: number;
  resourceType?: ResourceType;
  target?: string;
}

export interface EventCondition {
  type: 'min_crew' | 'max_crew' | 'has_room' | 'has_tech' | 'min_resource' | 'time_played';
  value: number | string;
}

