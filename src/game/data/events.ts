// Get events by category
export const getEventsByCategory = (category: EventCategory): EventDefinition[] => {
  return GAME_EVENTS.filter((event) => event.category === category);
};

// Get events by severity
export const getEventsBySeverity = (severity: EventSeverity): EventDefinition[] => {
  return GAME_EVENTS.filter((event) => event.severity === severity);
};

// Roll for random event
export const rollForEvent = (dayMultiplier: number = 1): EventDefinition | null => {
  // Shuffle events and check probabilities
  const shuffled = [...GAME_EVENTS].sort(() => Math.random() - 0.5);

  for (const event of shuffled) {
    if (Math.random() < event.probability * dayMultiplier) {
      return event;
    }
  }

  return null;
};

// Get total event count
export const getTotalEventCount = (): number => {
  return GAME_EVENTS.length;
};
